import assert from "node:assert/strict";
import {WIZARD_STEPS_570,WIZARD_OPTIONS_570,createWizardState570,selectWizardOption570,canAdvanceWizard570,moveWizard570,wizardReview570} from "../assets/quote-first-wizard-model-v570.js";
assert.deepEqual(WIZARD_STEPS_570,["vehicle","goal","condition","extras","review"]);
let state=createWizardState570();
assert.equal(canAdvanceWizard570(state),false);
assert.equal(moveWizard570(state,"next").step,0);
assert.equal(selectWizardOption570(state,"vehicle","fake"),state);
state=selectWizardOption570(state,"vehicle","mid");
assert.equal(canAdvanceWizard570(state),true);
state=moveWizard570(state,"next");assert.equal(state.step,1);
state=selectWizardOption570(state,"goal","interior");
state=moveWizard570(state,"next");assert.equal(state.step,2);
assert.equal(canAdvanceWizard570(state),false);
state=selectWizardOption570(state,"condition","heavy");
state=moveWizard570(state,"next");assert.equal(state.step,3);
assert.equal(canAdvanceWizard570(state),true);
state=selectWizardOption570(state,"extras","pet_hair");
assert.deepEqual(state.extras,["pet_hair"]);
state=selectWizardOption570(state,"extras","pet_hair");
assert.deepEqual(state.extras,[]);
state=selectWizardOption570(state,"extras","salt");
state=moveWizard570(state,"next");assert.equal(state.step,4);
assert.equal(canAdvanceWizard570(state),false);
assert.equal(moveWizard570(state,"next").step,4);
const r=wizardReview570(state);
assert.equal(r.vehicle,"SUV / crossover");
assert.equal(r.goal,"Deep interior clean");
assert.equal(r.condition,"Needs assessment");
assert.deepEqual(r.extras,["Salt / winter stains"]);
assert.equal(r.estimate_status,"Not quoted");
for(const k of ["contact_collected","request_submitted","availability_checked","booking_confirmed","payment_collected","public_wizard_enabled"])assert.equal(r[k],false);
assert.ok(Object.isFrozen(r));
state=moveWizard570(state,"back");assert.equal(state.step,3);
assert.equal(WIZARD_OPTIONS_570.extras.length,5);
console.log("Build 570 preview-only quote journey: PASS (no live quotes/bookings/payments)");
