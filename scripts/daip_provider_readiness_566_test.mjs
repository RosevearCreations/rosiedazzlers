import assert from 'node:assert/strict';
import {REQUIRED_PROVIDER_NAMES_566,EXTERNAL_EVIDENCE_566,reconcileProviderReadiness566} from '../assets/daip-provider-readiness-566.js';
const empty=reconcileProviderReadiness566();
assert.equal(empty.operational_status,'HOLD');
assert.equal(empty.missing_declaration_names.length,7);
assert.equal(empty.unverified_external_evidence.length,6);
assert.equal(empty.public_release_allowed,false);
const full=reconcileProviderReadiness566({declaredVariableNames:[...REQUIRED_PROVIDER_NAMES_566]});
assert.equal(full.missing_declaration_names.length,0);
assert.equal(full.credential_configuration_verified,false);
assert.equal(full.private_runtime_accepted,false);
assert.equal(full.operational_status,'HOLD');
const partial=reconcileProviderReadiness566({declaredVariableNames:['SUPABASE_URL','SUPABASE_URL','not-a-credential','TOP_SECRET_VALUE']});
assert.deepEqual(partial.declared_names,['SUPABASE_URL']);
assert.equal(partial.missing_declaration_names.length,6);
assert.equal(partial.public_export_allowed,false);
assert.equal(partial.worker_dispatched,false);
assert.equal(partial.storage_written,false);
assert.ok(!JSON.stringify(partial).includes('TOP_SECRET_VALUE'));
assert.equal(EXTERNAL_EVIDENCE_566.length,6);
console.log('Build 566 non-secret provider readiness inventory: PASS (all runtime/public operations remain HOLD)');
