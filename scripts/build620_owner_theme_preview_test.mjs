import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { clonePreviewTheme, contrastRatio, exportReviewReceipt, STANDARD_PALETTE, validateThemeDraft } from '../assets/theme-preview-contract.js';

const config=JSON.parse(readFileSync(new URL('../data/theme_preview_registry.json',import.meta.url)));
const slots=JSON.parse(readFileSync(new URL('../data/standard_theme_image_slots.json',import.meta.url)));
assert.equal(config.previewOnly,true);
assert.equal(config.activePublicTheme,'standard');
assert.ok(slots.entries.length>15);
assert.ok(contrastRatio(STANDARD_PALETTE.text,STANDARD_PALETTE.background)>4.5);
const draft=clonePreviewTheme(config.baseline,'studio-gold','Studio Gold');
assert.equal(draft.version,2);
assert.equal(draft.status,'owner_review_draft');
assert.equal(draft.parent.id,'standard');
assert.deepEqual(validateThemeDraft(draft),[]);
assert.notEqual(draft.palette,config.baseline.palette);
draft.palette.accent='#aabbcc';
assert.equal(config.baseline.palette.accent,'#dec06d');
assert.ok(validateThemeDraft({...draft,palette:{...draft.palette,text:'#0b0e11'}}).some(x=>x.includes('contrast')));
assert.ok(validateThemeDraft({...draft,status:'active'}).length);
assert.throws(()=>clonePreviewTheme(config.baseline,'../../bad','Bad'));
draft.review={acknowledged:true,notes:'Reviewed with visible focus and separate media ownership'};
const receipt=exportReviewReceipt(draft,'owner@example.test');
assert.equal(receipt.publicActivation,false);
assert.equal(receipt.decision,'preview_reviewed_only');
assert.equal(receipt.theme.slots.managed && typeof receipt.theme.slots.managed,'object');
const page=readFileSync(new URL('../admin-theme-manager.html',import.meta.url),'utf8');
assert.match(page,/assets\/admin-auth\.js/);
assert.match(page,/assets\/admin-shell\.js/);
assert.match(page,/aria-live="polite"/);
assert.doesNotMatch(page,/type="submit"/);
console.log('Build 620 owner theme preview contract checks passed.');
