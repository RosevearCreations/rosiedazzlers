import assert from "node:assert/strict";
import {validateDecision,reconcileDecision,recoveryFollowUp} from "./release_incident_decision_ledger.mjs";
const sha="a".repeat(40), id="incident-578", owner="RosevearCreations";
const base={incidentSha:sha,decisionId:id,action:"request-retry",owner,reason:"Investigate stalled exact-main release",state:"PROPOSED"};
const approved={...base,state:"OWNER_APPROVED",evidenceRef:"issue:123",approvalRef:"comment:456"};
const executed={...approved,state:"EXECUTED",executionRef:"run:789"};
const verified={...executed,state:"VERIFIED",verifiedMainSha:sha,productionProofRef:"cloudflare:receipt-1",businessProofRef:"github:acceptance-2"};
assert.equal(validateDecision(base).state,"PROPOSED");
let history=reconcileDecision([],base);
history=reconcileDecision(history,approved);
history=reconcileDecision(history,executed);
history=reconcileDecision(history,verified);
assert.equal(history.length,4);
assert.throws(()=>reconcileDecision(history,verified),/Illegal or duplicate/);
assert.throws(()=>reconcileDecision([],approved),/start PROPOSED/);
assert.throws(()=>validateDecision({...base,action:"rollback-now"}),/Unsupported/);
assert.throws(()=>validateDecision({...executed,approvalRef:undefined}),/owner approval/);
assert.throws(()=>validateDecision({...verified,verifiedMainSha:"b".repeat(40)}),/mismatch/);
const required={"Cloudflare Pages":"success","Verify exact Production deployment":"success","Validate Production business acceptance source contract":"success"};
const health={state:"GREEN",mainSha:sha,productionSha:sha,required};
assert.equal(recoveryFollowUp({decision:verified,health}).accepted,true);
assert.equal(recoveryFollowUp({decision:executed,health}).accepted,false);
assert.equal(recoveryFollowUp({decision:verified,health:{...health,productionSha:"b".repeat(40)}}).accepted,false);
assert.equal(recoveryFollowUp({decision:verified,health:{...health,state:"DRIFT"}}).accepted,false);
assert.equal(recoveryFollowUp({decision:verified,health:{...health,required:{}}}).accepted,false);
console.log("Build 578 decision ledger and follow-up checks PASS");
