import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const read=p=>readFileSync(new URL('../'+p,import.meta.url),'utf8');
const dashboard=read('admin.html');
const login=read('admin-login.html');
const css=read('assets/build648-admin-operator.css');
const logic=read('assets/build648-admin-operator.js');
assert.equal(dashboard,read('admin/index.html'),'Admin dashboard route copies must match');
assert.equal(login,read('admin-login/index.html'),'Staff-login route copies must match');
for(const s of ['data-admin-shell-ready','window.AdminShell.boot','data-admin-logout','dashboardKpis','paymentWebhookWarnings'])assert.ok(dashboard.includes(s),'Existing protected dashboard contract: '+s);
for(const s of ['adminToolSearch','adminToolCategory','adminToolClear','adminToolCount','adminWorkspaceCards','adminDiagnostics'])assert.ok(dashboard.includes(s),'Operator control: '+s);
for(const href of ['/admin-today.html','/admin-booking.html','/admin-leads.html','/admin-inventory-manager.html','/admin-photo-studio.html','/admin-payments.html'])assert.ok(dashboard.includes('href="'+href+'"'),'Quick link: '+href);
assert.equal((dashboard.match(/<details\b/g)||[]).length,(dashboard.match(/<\/details>/g)||[]).length,'Diagnostics disclosure valid');
assert.match(logic,/card\.hidden=!/,'Visible card filtering must work');
assert.match(logic,/search\.addEventListener\('input',filter\)/,'Search updates on typing');
assert.match(logic,/category\.addEventListener\('change',filter\)/,'Group updates selection');
assert.match(logic,/clear\.addEventListener\('click'/,'Clear filters is interactive');
assert.doesNotMatch(logic,/fetch\(|localStorage|sessionStorage|innerHTML/,'Admin navigation must not access customer data or mutate server');
for(const selector of ['#adminWorkspaceCards','.admin-diagnostics','.admin-tool-controls','body.admin-staff-login'])assert.ok(css.includes(selector),'Scoped stylesheet '+selector);
for(const size of ['800px','540px'])assert.ok(css.includes(size),'Tablet and mobile breakpoint '+size);
assert.match(login,/id="staff-login-form"/);
assert.match(login,/window\.AdminAuth\.signIn/,'Preserve real sign-in flow');
assert.match(login,/window\.AdminAuth\.readNextUrl/,'Preserve approved return URL');
assert.match(login,/id="staff-login-status".*aria-live="polite"/,'Accessible auth status');
assert.match(read('scripts/current_source_gate_contracts.sh'),/node scripts\/build648_admin_operator_test\.mjs/,'Keep regression wired to source gate');
console.log('Build 648 Admin Operator Workspace: PASS');
